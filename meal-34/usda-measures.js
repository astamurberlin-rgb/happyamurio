/* перевод хвоста подписи: самый длинный оборот — первым */
function translate(s,head,tokens,brands){
 TOK.cur=tokens;var out='',g=head?head.g:'m',box=head?head.box:false,guard=0,m;
 while(s.length&&guard++<400){
  var c=s[0];
  if(c==='⟪'){m=s.match(/^⟪(\d+)⟫/);out+=brands[+m[1]];s=s.slice(m[0].length);continue}
  if(c==='⟦'){m=s.match(/^⟦(\d+)⟧\s*/);var t=tokens[+m[1]];s=s.slice(m[0].length);
   if(t.k==='n'){
    var cm=longest(CNT_RE,s);
    if(cm){out+=nText(t)+' '+(t.b!=null?cm.x.f[2]:plural(nValue(t),cm.x.f))+' ';s=s.slice(cm.m[0].length);continue}
    out+=nText(t)+' ';continue;
   }
   out+='⟦'+m[1]+'⟧ ';continue;
  }
  if(!/[A-Za-z]/.test(c)){out+=c;s=s.slice(1);continue}
  var q=longest(Q_RE,s),w=longest(W_RE,s),h=longest(HEADS_RE,s),best=null,ru;
  [q&&{k:'q',v:q},w&&{k:'w',v:w},h&&{k:'h',v:h}].forEach(function(x){if(x&&(!best||x.v.m[0].length>best.v.m[0].length))best=x});
  if(best){
   var mm=best.v.m,x=best.v.x;
   if(best.k==='q')ru=typeof x.ru==='string'?x.ru:(box?x.ru.gen:x.ru[g]||x.ru.m);
   else if(best.k==='w')ru=typeof x.ru==='function'?x.ru.apply(null,mm):mm[0].replace(x.re,x.ru);
   else ru=x.ru;
   s=s.slice(mm[0].length);
   /* в обороте могли остаться английские слова: переводим их тем же порядком */
   if(best.k==='w'&&/[A-Za-z]/.test(ru))ru=translate(ru,head,tokens,brands);
   out+=ru;continue;
  }
  m=s.match(/^[A-Za-z][\w'’&!-]*/);out+=m[0];s=s.slice(m[0].length);
 }
 return out;
}
function tidy(s){
 return s.replace(/\(\s*\)/g,'').replace(/\s+([,)])/g,'$1').replace(/\(\s+/g,'(').replace(/,\s*,/g,',').replace(/\s{2,}/g,' ')
  .replace(/,\s*\)/g,')').replace(/\(\s*,/g,'(').replace(/^[,\s]+|[,\s]+$/g,'').replace(/\)\s*\(/g,', ').replace(/\b1 (порция с этикетки США)/g,'$1')
  .replace(/\s[x×]\s/g,' × ').replace(/\bна столовая ложка/g,'на столовую ложку').replace(/(^|[\s(])на чайная ложка/g,'$1на чайную ложку').replace(/(^|[\s(])на столовая ложка/g,'$1на столовую ложку').replace(/(^|[\s(])на чашка США/g,'$1на чашку США').replace(/(^|[\s(])мини (?=[а-яё])/g,'$1мини-').replace(/⌀\s+/g,'⌀ ').trim();
}
/* метки → числа; внутри скобок объём чашки — через запятую: «(⅛ чашки США, 30 мл)» */
function render(s,tokens,mode){
 var out='',depth=0;
 for(var i=0;i<s.length;i++){
  var c=s[i];
  if(c==='(')depth++;else if(c===')')depth--;
  if(c==='⟦'){var m=s.slice(i).match(/^⟦(\d+)⟧/),txt=qty(tokens[+m[1]],mode);if(depth>0)txt=txt.replace(/ \(([^()]*)\)$/,', $1');out+=txt;i+=m[0].length-1;continue}
  out+=c;
 }
 return out;
}

