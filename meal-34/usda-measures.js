/* количества → метки ⟦n⟧; фирменные названия → ⟪n⟫ */
function tokenize(s,tokens,brands){
 s=s.replace(BRAND,function(b){brands.push(b);return '⟪'+(brands.length-1)+'⟫'});
 var out='',i=0,m;
 var rx=new RegExp('^('+NUM+')(?:\\s*(?:-|to|–)\\s*('+NUM+'))?\\s*');
 var dim=new RegExp('^('+NUM+')\\s*"?\\s*[x×]\\s*('+NUM+')\\s*"?(?:\\s*[x×]\\s*('+NUM+')\\s*")?');
 while(i<s.length){
  var rest=s.slice(i),prev=s[i-1]||' ';
  if(/[\d.]/.test(rest[0])&&!/[A-Za-z\d#⟪⟫]/.test(prev)&&!(prev==='-'&&/[A-Za-z]/.test(s[i-2]||''))){
   if((m=rest.match(dim))&&/"/.test(m[0])){tokens.push({k:'dim',list:[m[1],m[2],m[3]].filter(Boolean).map(num)});out+='⟦'+(tokens.length-1)+'⟧';i+=m[0].length;continue}
   if((m=rest.match(rx))){
    var after=rest.slice(m[0].length),u=null;
    for(var j=0;j<UNIT.length;j++){var um=after.match(UNIT[j][0]);if(um){u={k:UNIT[j][1],u:UNIT[j][2],len:um[0].length};break}}
    if(u&&u.u==='l'&&!/^l\b(?!b)/.test(after)&&!/^lit/i.test(after))u=null;
    if(u&&u.u==='tbsp'&&/^T\b/.test(after)&&!/^T\s+dry/.test(after))u=null;
    if(u){tokens.push({k:u.k,u:u.u,a:num(m[1]),b:m[2]?num(m[2]):null});out+='⟦'+(tokens.length-1)+'⟧';i+=m[0].length+u.len;continue}
    /* голое число: «(28 almonds)», «2 slices», «1/8 of» */
    tokens.push({k:'n',a:num(m[1]),b:m[2]?num(m[2]):null});out+='⟦'+(tokens.length-1)+'⟧ ';i+=m[0].length;continue;
   }
  }
  out+=s[i];i++;
 }
 out=out.replace(/\s+/g,' ').trim();
 /* «3" to 4-1/4"» — один диапазон */
 out=out.replace(/⟦(\d+)⟧\s*(?:to|-|–)\s*⟦(\d+)⟧/g,function(all,a,b){var x=tokens[+a],y=tokens[+b];if(x.k===y.k&&x.k!=='n'&&x.k!=='dim'&&x.u===y.u&&x.b==null&&y.b==null){x.b=y.a;return '⟦'+a+'⟧'}return all});
 out=out.replace(/⟦(\d+)⟧\s*or\s*⟦(\d+)⟧/g,function(all,a,b){var x=tokens[+a],y=tokens[+b];if(x.k==='len'&&y.k==='len'&&x.b==null&&y.b==null){y.or=x.a;return '⟦'+b+'⟧'}return all});
 out=out.replace(/⟦(\d+)⟧\s*(pieces|cubes|slices|chunks)\b/gi,function(all,i,w){return tokens[+i].k==='len'?w+' по ⟦'+i+'⟧':all});
 out=out.replace(/⟦(\d+)⟧\s*(bar|bag|pack|package|box|tube|bottle|can|container|pouch|cup|pizza|pie|pkg)\b/gi,function(all,i,w){var k=tokens[+i].k;return k==='m'||(k==='v'&&tokens[+i].u!=='cup')?w+' ⟦'+i+'⟧':all});
 /* размеры: «9" dia» → «⌀ 23 см», «5" long» → «длина 13 см» */
 out=out.replace(/⟦(\d+)⟧\s*(dia|diameter|long|thick|high|wide|square|sq|base)\b\.?(?:,?\s*(sphere))?/gi,function(all,i,w,sp){var t=tokens[+i];if(t.k!=='len'&&t.k!=='dim')return all;w=w.toLowerCase();
  if(t.k==='dim')return '⟦'+i+'⟧'+(w==='square'||w==='sq'?' квадрат':'');
  return ({dia:'⌀ ',diameter:'⌀ ',long:'длина ',thick:'толщина ',high:'высота ',wide:'ширина ',base:'основание '}[w]||'')+'⟦'+i+'⟧'+(w==='square'||w==='sq'?' квадрат':'')+(sp?' шар':'')});
 return out;
}
function nText(t){return t.b!=null?count(t.a)+'–'+count(t.b):count(t.a)}
