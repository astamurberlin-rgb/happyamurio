        code, family = selected['code'], selected['family']
        source = tables['main'][code]
        nut, qualifiers = dict.fromkeys(canonical), {}
        field_sources = {}
        for table, mapping in [('main',MAIN_MAP),('aa',AA_MAP),('fat',FAT_MAP),('carb',CARB_MAP)]:
            row = tables[table].get(code)
            for key, col in mapping.items():
                factor = .001 if table=='aa' or key in ('bcar','la','ala3') else 1
                nut[key], qualifiers[key] = parse_value(row[col] if row else None,factor)
                qualifiers[key]['table'] = table
                if row is None:
                    qualifiers[key]['reason'] = 'food_not_in_supplemental_table'
                field_sources[key] = table
        for key in canonical:
            if key not in qualifiers:
                qualifiers[key]={'raw':None,'state':'missing','estimated':False,'reason':'not_mapped'}
