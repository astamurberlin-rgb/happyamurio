        columns[name] = {str(i):str(v).strip() for i,v in enumerate(identifiers) if i>=4 and v is not None}
        provenance[name] = {'url':url,'sha256':hashlib.sha256(path.read_bytes()).hexdigest(),
                            'records':len(tables[name]),'table':'第2章 第1表' if name in ('aa','fat') else '第2章 本表'}
