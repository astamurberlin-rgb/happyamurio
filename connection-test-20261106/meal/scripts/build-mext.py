def parse_value(raw, factor=1):
    if raw is None:
        return None, {'raw': None, 'state': 'missing', 'estimated': False}
    text = str(raw).strip().replace('−','-').replace('（','(').replace('）',')')
    estimated = text.startswith('(') and text.endswith(')')
    bare = text[1:-1].strip() if estimated else text
    q = {'raw': raw, 'state':'value', 'estimated': estimated}
    if bare.lower() == 'tr':
        q['state'] = 'trace'
        return None, q
    if bare in ('','-','―','—'):
        q['state'] = 'missing'
        return None, q
    if not re.fullmatch(r'\d+(?:\.\d+)?', bare):
        raise ValueError(f'Unexpected MEXT marker: {raw!r}')
    return round(float(bare) * factor, 10), q

def read_table(path):
    wb = openpyxl.load_workbook(path, read_only=True, data_only=True)
    rows = list(wb['表全体'].values)
    data = {str(row[1]):row for row in rows if len(row)>3 and re.fullmatch(r'\d{5}', str(row[1]))}
    wb.close()
    return data, rows

def read_selection():
    chosen, families, seen = [], {}, set()
    family = None
    for line in SELECTION.strip().splitlines():
        parts = line.split('|')
        if line.startswith('@'):
            family, ru, en = parts
            family = family[1:]
            families[family] = {'ru':ru,'en':en}
        else:
            code, ru, en = parts
            if code in seen:
                raise ValueError(f'Duplicate selected food code {code}')
            seen.add(code)
            chosen.append({'code':code,'family':family,'variant':{'ru':ru,'en':en}})
    return chosen, families

