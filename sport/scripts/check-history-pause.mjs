import {readFile} from 'node:fs/promises';
import {createContext,runInContext} from 'node:vm';
import assert from 'node:assert/strict';
const pause=await readFile(new URL('../src/workout-pause.js',import.meta.url),'utf8');
const history=await readFile(new URL('../src/exercise-history.js',import.meta.url),'utf8');
const c=createContext({document:{addEventListener(){}},localNow:()=> '2026-10-25T12:10:00'});
runInContext(pause,c);
c.w={start:'2026-10-25T12:00:00'};
runInContext("toggleWorkoutPause(w,'2026-10-25T12:02:00')",c);
assert.equal(runInContext('workoutActiveSeconds(w)',c),120);
c.w=JSON.parse(JSON.stringify(c.w));
assert.equal(runInContext('workoutIsPaused(w)',c),true,'Pause survives reload');
runInContext("toggleWorkoutPause(w,'2026-10-25T12:05:00')",c);
assert.equal(runInContext('workoutActiveSeconds(w)',c),420);
runInContext("toggleWorkoutPause(w,'2026-10-25T12:08:00');closeWorkoutPause(w,'2026-10-25T12:10:00')",c);
assert.equal(runInContext('workoutActiveSeconds(w)',c),300,'Multiple pauses are excluded on finish');
assert.equal(runInContext("workoutActiveSeconds(w,'2026-10-25T12:04:00','2026-10-25T12:09:00')",c),180,'Edited boundaries clip pause intervals');
assert.equal(runInContext("workoutActiveSeconds({start:'2026-10-25T12:00:00'})",c),600);
c.w.pauses.push({start:'2026-10-25T12:02:00',end:'2026-10-25T12:05:00'});
assert.equal(runInContext('workoutActiveSeconds(w)',c),300,'Overlapping pause intervals are counted once');
const profiles={lift:'load_reps',swim:'distance_time',body:'reps'};
const h=createContext({document:{addEventListener(){}},state:{workouts:[]},exercise:id=>({id,name:id,profile:profiles[id]}),isLoaded:e=>profiles[e.id]==='load_reps',hasDistance:e=>e?.profile==='distance_time',isTimed:e=>profiles[e.id]==='distance_time',fmt:String,durationText:s=>s+' сек',esc:String,shortDate:String});
runInContext(history,h);
const workout=(id,start,sets,eid='lift')=>({id,start,exercises:[{id:eid,sets}]});
h.state.workouts=[workout('old','2026-10-01T12:00',[{weight:80,reps:5,done:true},{weight:90,reps:3,done:false}]),workout('new','2026-10-20T12:00',[{weight:70,reps:10,done:true}]),{...workout('demo','2026-10-24T12:00',[{weight:500,reps:10,done:true}]),demo:true},workout('variant','2026-10-24T12:00',[{weight:1000,reps:5,done:true}],'other')];
let rows=runInContext("exerciseHistoryEntries('lift')",h);
assert.equal(rows.length,2);assert.equal(rows[0].best,80);assert.equal(rows[0].volume,400);assert.equal(rows[0].duration,null);
h.rows=rows;
assert.equal(runInContext("sortedExerciseHistory(rows,'date')[0].id",h),'new');
assert.equal(runInContext("sortedExerciseHistory(rows,'best')[0].id",h),'old');
assert.match(runInContext("exerciseHistoryBody('lift','duration')",h),/время не записано/);
h.state.workouts=[workout('short','2026-10-20T12:00',[{seconds:60,distance:100,done:true}],'swim'),workout('long','2026-10-01T12:00',[{seconds:120,distance:200,done:true},{seconds:60,distance:100,done:true}],'swim')];
assert.equal(runInContext("sortedExerciseHistory(exerciseHistoryEntries('swim'),'duration')[0].id",h),'long');
assert.equal(runInContext("exerciseHistoryEntries('swim')[1].duration",h),180);
assert.equal(runInContext("exerciseHistoryEntries('swim')[1].distance",h),300);
console.log('Passed: pause persistence/finish/edit bounds, history excludes unfinished/demo/other variants, sorting and timed/distance totals.');
