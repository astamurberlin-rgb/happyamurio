import {readFile} from 'node:fs/promises';
import {createContext,runInContext} from 'node:vm';
import assert from 'node:assert/strict';

const read=name=>readFile(new URL('../src/'+name+'.js',import.meta.url),'utf8');
const handlers={};
const c=createContext({console,Date,Math,Number,JSON,setInterval(){},document:{addEventListener(type,fn){(handlers[type]??=[]).push(fn);},querySelector(){return null;}},nav(){},openSheet(){},closeSheet(){},persist(){},toast(){},icon:n=>'<svg>'+n+'</svg>',esc:s=>String(s),$:()=>null});
runInContext(`var SEED={exercises:[{id:'hold',name:'Планка',profile:'hold',metrics:['seconds']}]};
var state={workouts:[],customExercises:[],active:{start:'2026-10-29T12:00:00',pauses:[],exercises:[{id:'hold',name:'Планка',sets:[{seconds:60,done:false}],timerConfig:{mode:'stopwatch'}}]}};
var now='2026-10-29T12:00:00.000',localNow=()=>now.slice(0,19),clone=x=>JSON.parse(JSON.stringify(x)),exercise=id=>state.exerciseOverrides?.[id]||SEED.exercises.find(e=>e.id===id);
function blankSet(){return {seconds:0,done:false}}`,c);
runInContext(await read('metric-field'),c);
runInContext((await read('timer-action-wheel')).split('function timerWheelContext(')[0],c);
const config=await read('exercise-config');
runInContext(config.slice(0,config.indexOf('// Shared editor')),c);
runInContext((await read('workout-pause')).split('document.addEventListener')[0],c);
runInContext(await read('set-time'),c);
runInContext(await read('exercise-player'),c);
const run=code=>runInContext(code,c),plain=x=>JSON.parse(JSON.stringify(x));
run('playerNow=()=>now');

assert.equal(run('playerCanAddRound(playerPreview(0))'),false,'No lap before a stopwatch starts');
assert.equal(run('addPlayerRound(0)'),false);
assert.match(run('exercisePlayerBody(0)'),/Круг 1/);
assert.match(run('exercisePlayerBody(0)'),/>START</);
assert.equal(run('playerDisplay(0,true)'),'00:00.00');
