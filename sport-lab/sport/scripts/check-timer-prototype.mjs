assert.match(run('exercisePlayerBody(0)'),/Таймер 2/);
assert.equal(run('parsePlayerPreset("01:30.00")'),90);
run('commitPlayerPreset({dataset:{playerPreset:"0,1,workSeconds"},value:"00:30"})');
run('commitPlayerPreset({dataset:{playerPreset:"0,0,workSeconds"},value:"01:00"})');
assert.equal(run('playerProgram(playerPreview(0))[1].workSeconds'),30);
run("now='2026-10-29T13:00:00.000';toggleExercisePlayer(0,now);now='2026-10-29T13:00:10.250'");
assert.equal(run('playerRoundRemaining(state.active.exercisePlayer,0,"workSeconds",now)'),49.75);
assert.equal(run('addPlayerRound(0,now)'),true,'A running timer accepts the next timer without losing its anchor');
