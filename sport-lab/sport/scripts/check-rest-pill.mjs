import {readFile} from 'node:fs/promises';
import {createContext,runInContext} from 'node:vm';
import assert from 'node:assert/strict';
const read=name=>readFile(new URL('../src/'+name+'.js',import.meta.url),'utf8');
const c=createContext({Date,Math,Number,console,document:{addEventListener(){},querySelector(){return null}},persist(){},toast(){},icon:x=>x,esc:x=>x});
runInContext(`var now='2026-10-29T12:00:00',localNow=()=>now,state={active:{start:now,pauses:[],exercises:[{id:'test',sets:[{reps:10,done:true,restSeconds:60}]}]}};`,c);
for(const file of ['workout-pause','set-rest','set-countdown','set-time'])runInContext(await read(file),c);
const player=await read('exercise-player');runInContext(player.slice(0,player.indexOf('function playerDisplay')),c);
const pill=await read('rest-pill');runInContext(pill.slice(0,pill.indexOf('function floatingRestMarkup')),c);
const run=code=>runInContext(code,c);
run('playerNow=()=>now');
run("startSetCountdown('rest',0,0,now);now='2026-10-29T12:00:20'");
assert.equal(run('activeRestContext().remaining'),40);
run('extendFloatingRest()');assert.equal(run('activeRestContext().remaining'),70);
run('toggleSetCountdown("rest",0,0);now="2026-10-29T12:10:00"');
assert.equal(run('activeRestContext().remaining'),70,'Pausing freezes the floating rest');
run('setFloatingRestTime("0:45")');assert.equal(run('activeRestContext().remaining'),45);assert.equal(run('activeRestContext().running'),false);
assert.equal(run('state.lastRestSeconds'),45);assert.equal(run('setFloatingRestTime("bad")'),false);
run('toggleSetCountdown("rest",0,0);now="2026-10-29T12:11:00";updateSetCountdown()');
assert.equal(run('activeRestContext().finished'),true,'Expired rest stays available for extension');
run('extendFloatingRest()');assert.equal(run('activeRestContext().remaining'),30);assert.equal(run('activeRestContext().running'),true);
c.state=JSON.parse(JSON.stringify(c.state));assert.equal(run('activeRestContext().remaining'),30,'Floating rest survives JSON reload');
run('finishFloatingRest()');assert.equal(run('activeRestContext()'),null);assert.equal(run('state.active.exercises[0].sets[0].restDone'),true);
run(`state.active.countdown=null;state.active.exercises[0].sets=[{seconds:20,done:true,restSeconds:10},{seconds:40,done:false}];state.active.exercisePlayer={ei:0,mode:'intervals',workSeconds:20,restSeconds:10,rounds:2,program:[{workSeconds:20,restSeconds:10},{workSeconds:40,restSeconds:0}],setIndices:[0,1],startedAt:now,elapsed:23,running:false,finished:false,completedRounds:1,laps:[]}`);
assert.equal(run('activeRestContext().remaining'),7);
run('setFloatingRestTime("0:12")');assert.equal(run('activeRestContext().remaining'),12);
run('finishFloatingRest()');assert.equal(run('activeRestContext()'),null);assert.equal(run('exercisePlayerStatus(state.active.exercisePlayer).round'),2);
console.log('Passed: floating rest pause, extension, editing, expiry/restart, reload, finish and interval-player rest skip.');

runInContext(pill.slice(pill.indexOf('function restPillBottom('),pill.indexOf('function positionFloatingRest(')),c);
assert.equal(run('restPillBottom(900,900,0,null,0)'),100);
assert.equal(run('restPillBottom(900,900,0,760,0)'),152,'Rest is above the collapsed workout banner');
assert.equal(run('restPillBottom(900,500,0,760,0)'),412,'Rest lifts above the keyboard');
assert.equal(run('restPillBottom(900,450,50,null,0)'),412,'Viewport panning is included');
assert.equal(run('restPillBottom(500,500,0,360,0)'),152,'Resize-mode keyboards preserve the banner stack');
console.log('Passed: rest pill banner stack, keyboard resize and viewport panning.');
