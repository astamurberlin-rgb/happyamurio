"""Три правки по проверке «не спорят ли знания» (да Астамура 23.11.2026): горит масло, фаршированные овощи, «на ночь».
Запуск ПОСЛЕ сведения всех веток: python3 fix3.py merged.json out.json
Меняет только слова, на которые карточки откликаются (said / not); ответы и источники не трогает.
Карточки нет в файле — пропуск с пометкой. Слова карточки уже не те, что ждёт скрипт, — остановка (сначала свериться руками)."""
import json, sys

OIL = r"(масл|сковород|жир|фритюр|кастрюл)"
# точно пожар: «загорелось», «горящее масло», «масло горит», «горит сковорода», «чем тушить масло»
FIRE = (r"загор|вспыхн|воспламен|горящ|(масло|жир|сковорода|сковородка|фритюр|кастрюля)\s+(сильно\s+)?гор(ит|ят)"
        r"|гор(ит|ят)\s+(масл|жир|сковород|фритюр|кастрюл)|тушить\s+(масло|жир|сковород|фритюр|огонь|пламя|пожар)")
HEAT = r"убав|сильн\S* огон|слаб\S* огон|средн\S* огон|на каком огне|на огне"   # «на каком огне жарить» — не пожар

PATCH = [
 # 1. Горит масло: карточка пожара знает «горит», «горящее», «потушить»; соседи на эти слова молчат
 dict(id="fry-pozhar",
      old=dict(said=r"(?=.*(загорел|вспыхнул|воспламен|пожар|пламя|огонь|полыха))(?=.*(масл|сковород|жир|фритюр|кастрюл))",
               **{"not": r"сливочн|убав|сильн\S* огон|слаб\S* огон|средн\S* огон|на каком огне|на огне"}),
      new=dict(said=r"^(?=.*" + OIL + r")(?:(?=.*(" + FIRE + r"))|(?!.*(" + HEAT + r"))(?=.*(пожар|пламя|огонь|полыха)))",
               **{"not": r"сливочн"})),
 dict(id="fry-prigoraet",
      old={"not": r"чеснок|сливочн|загорел|пожар|пламя|огонь в|вспыхн|температур|градус"},
      new={"not": r"чеснок|сливочн|пожар|пламя|огонь в|температур|градус|" + FIRE}),
 dict(id="tip-ne-tushit", old={"not": None},
      new={"not": r"загор|вспыхн|воспламен|пожар|пламя|полыха|горящ|(масло|жир|сковорода|сковородка)\s+гор(ит|ят)|гор(ит|ят)\s+(масл|жир|сковород)"}),
 dict(id="tip-tushit", old={"not": r"тушенк|тушонк|тушк"},
      new={"not": r"тушенк|тушонк|тушк|загор|вспыхн|воспламен|пожар|пламя|полыха|горящ"}),
 # 2. Фаршированные овощи: запекание овощей молчит, когда внутри фарш или мясо — отвечает карточка фарша, как на сайте
 dict(id="zapek-ovoshchi",
      old={"not": r"калори|ккал|бжу|белк|углевод|запиш|запис|добав|удали|брокколи|брокол|морков|свекл|картош|картоф"},
      new={"not": r"калори|ккал|бжу|белк|углевод|запиш|запис|добав|удали|брокколи|брокол|морков|свекл|картош|картоф|фарш|начин|мяс|говяд|баран|телят|голубц"}),
 dict(id="zapek-kartofel",
      old={"not": r"калори|ккал|бжу|белк|углевод|запиш|запис|добав|удали"},
      new={"not": r"калори|ккал|бжу|белк|углевод|запиш|запис|добав|удали|фарш|начин"}),
 # 3. «На ночь»: совет о еде перед сном молчит, когда вопрос про готовку и хранение
 dict(id="adv-noch", old={"not": None},
      new={"not": r"замоч|замач|вымач|остав|постав|убра(ть|л)|хран|\s(по|вы)?держат|\s(с|от|по|про)?варить|кипят|жарит|запек|запеч|тушит|испеч|солит|засол|посол|маринов|маринад|рассол|заквас|квасит|опар|тест(о|а|у|е|ом)\s|дрожж|размор|настаива|настоят|замес|залит|залив|на плите|в холодильник|морозилк|духовк|мультиварк|на столе"}),
]

def main(src, dst):
    d = json.load(open(src, encoding="utf-8")); by = {c["id"]: c for c in d["cards"]}; done = []
    for p in PATCH:
        c = by.get(p["id"])
        if not c: print("нет карточки, пропуск:", p["id"]); continue
        if all(c.get(k) == v for k, v in p["new"].items()): print("уже поправлена:", p["id"]); continue
        for k, v in p["old"].items():
            if c.get(k) != v: sys.exit("карточка %s: поле %s не то, что ждали:\n  есть: %r\n  ждали: %r" % (p["id"], k, c.get(k), v))
        for k, v in p["new"].items():
            if len(v) > 400: sys.exit("карточка %s: %s длиннее 400 знаков (%d)" % (p["id"], k, len(v)))
            c[k] = v
        done.append(p["id"])
    json.dump(d, open(dst, "w", encoding="utf-8"), ensure_ascii=False, separators=(",", ":"))
    print("поправлено:", ", ".join(done) or "ничего", "| карточек", len(d["cards"]))

if __name__ == "__main__": main(sys.argv[1], sys.argv[2])
