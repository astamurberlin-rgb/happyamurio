"""Правки по проверке «не спорят ли знания» (да Астамура 23.11.2026): горит масло, фаршированные овощи, «на ночь»;
плюс «пожар без вопроса» (да Астамура 24.11.2026 00:55 МСК): карточка пожара получает поле always — её слова для фраз без вопроса.
Запуск ПОСЛЕ сведения всех веток: python3 fix3.py merged.json out.json
Меняет только слова, на которые карточки откликаются (said / not / always); ответы и источники не трогает.
Карточки нет в файле — пропуск с пометкой. Слова карточки уже не те, что ждёт скрипт, — остановка (сначала свериться руками)."""
import json, sys

OIL = r"(масл|сковород|\sжир(а|у|ом|е)?[\s,]|фритюр|кастрюл)"          # «жир» — словом: «жирный», «обезжиренный» не считаются
VERB = r"загор(ел|ит|ят|евш|а[ею]т)|вспыхн|воспламен|полыха"              # загорелось, загорится, загоревшееся, загорается
POZHAR = r"\sпожар(а|у|е|ом)?[\s,]"                                         # слово «пожар», а не «пожарить»
NOUN = r"(масл|жир|сковород|фритюр|кастрюл)"
THING = r"(масло|жир|сковород(к)?а|фритюр\S*|кастрюля)"                    # что горит — именительный падеж: «масло горит», но не «на сковороде горят котлеты»
GAP = r"(\s+(на|в|во)\s+\S+)?"                                              # «масло НА СКОВОРОДЕ горит»
# явный пожар: «загорелось», «горящее масло», «масло горит», «горит сковорода», «чем тушить масло»
GORIT = r"\s" + THING + GAP + r"\s+гор(ит|ят)|\sгор(ит|ят)\s+" + NOUN
STRONG = VERB + r"|горящ\S*\s+" + NOUN + "|" + GORIT + r"|тушить\s+(масло|жир|сковород|фритюр|огонь|пламя|пожар)"
WEAK = POZHAR + r"|пламя|\sогонь[\s,]"
# «на каком огне жарить», «убавить огонь», «сильный огонь» — про нагрев, не про пожар
HEAT = r"убав|прибав|на\s+(\S+\s+)?огне|\S+(ый|ой|ий)\s+огонь|огонь\s+(под|нуж|долж|став|дел|как)"
# «при каком пульсе горит жир» — про похудение, не про пожар: «жир горит» считается только рядом с кухонным словом
SPORT = r"^(?=.*(жир\s+гор|гор(ит|ят)\s+жир))(?!.*(духов|сковор|плит|против|масл|кастрюл|фритюр|грил|загор|вспых))"
# соседние карточки на явный пожар молчат
FIRE_NOT = VERB + "|" + POZHAR + r"|пламя|горящ\S*\s+" + NOUN + "|" + GORIT
# фраза без вопроса («масло загорелось», «горит масло на сковороде»): что горит и «загорелось/горит» рядом
FIREV = r"(загорел(ось|ась|ся|ись)|загорается|вспыхнул[оаи]?|воспламенил(ось|ась|ся|ись)|полыхает)"   # «загорел на пляже» сюда не попадает
END = r"(?![а-я])"                                                          # конец слова: дальше пробел, запятая, «!» или конец фразы
ALWAYS = (r"\s" + THING + r"(\s+\S+){0,3}\s+" + FIREV + END + r"|\s" + FIREV + r"\s+" + THING + END
          + r"|\s" + THING + GAP + r"\s+гор(ит|ят)" + END + r"|\sгор(ит|ят)\s+" + THING + END
          + r"|\sгорящ\S*\s+(масло|жир|сковород|фритюр)|\sпожар\s+(на|в|во)\s+(сковород|фритюр|кастрюл)")

PATCH = [
 # 1. Горит масло: карточка пожара знает «горит», «горящее», «потушить»; соседи на эти слова молчат
 dict(id="fry-pozhar",
      old=dict(said=r"(?=.*(загорел|вспыхнул|воспламен|пожар|пламя|огонь|полыха))(?=.*(масл|сковород|жир|фритюр|кастрюл))",
               **{"not": r"сливочн|убав|сильн\S* огон|слаб\S* огон|средн\S* огон|на каком огне|на огне"}),
      new=dict(said=r"(?=.*" + OIL + r")(?=.*(" + STRONG + "|" + WEAK + r"))",
               always=ALWAYS,
               **{"not": r"сливочн|^(?!.*(загор|вспыхн|воспламен|горящ|полыха|\sгор(ит|ят)\s))(?=.*(" + HEAT + r"))|" + SPORT})),
 dict(id="fry-prigoraet",
      old={"not": r"чеснок|сливочн|загорел|пожар|пламя|огонь в|вспыхн|температур|градус"},
      new={"not": r"чеснок|сливочн|огонь в|температур|градус|" + FIRE_NOT}),
 dict(id="tip-ne-tushit", old={"not": None}, new={"not": FIRE_NOT}),
 dict(id="tip-tushit", old={"not": r"тушенк|тушонк|тушк"},
      new={"not": r"тушенк|тушонк|тушк|" + VERB + "|" + POZHAR + r"|пламя|горящ"}),
 # 2. Фаршированные овощи: запекание овощей и картофеля молчит, когда внутри фарш, — отвечает карточка фарша, как на сайте
 dict(id="zapek-ovoshchi",
      old={"not": r"калори|ккал|бжу|белк|углевод|запиш|запис|добав|удали|брокколи|брокол|морков|свекл|картош|картоф"},
      new={"not": r"калори|ккал|бжу|белк|углевод|запиш|запис|добав|удали|брокколи|брокол|морков|свекл|картош|картоф|фарш|начин|мяс|говяд|баран|телят|голубц"}),
 dict(id="zapek-kartofel",
      old={"not": r"калори|ккал|бжу|белк|углевод|запиш|запис|добав|удали"},
      new={"not": r"калори|ккал|бжу|белк|углевод|запиш|запис|добав|удали|фарш|начин"}),
 # 3. «На ночь»: совет о еде перед сном молчит, когда вопрос про готовку и хранение
 dict(id="adv-noch", old={"not": None},
      new={"not": r"замоч|замач|вымач|остав|постав|убра(ть|л)|хран|\s(по|вы)?держат|\s(с|от|по|про)?варить|кипят|жарит|запек|запеч|тушит|испеч|солит|засол|посол|маринов|маринад|рассол|заквас|квасит|опар|тест(о|а|у|е|ом)\s|дрожж|размор|настаива|настоят|замес|залит|залив|на плите|в холодильник|морозилк|духовк|мультиварк|на столе"}),
]

def main(src, dst):
    d = json.load(open(src, encoding="utf-8")); by = {c["id"]: c for c in d["cards"]}; done = []
    for p in PATCH:
        c = by.get(p["id"])
        if not c: print("нет карточки, пропуск:", p["id"]); continue
        if all(c.get(k) == v for k, v in p["new"].items()): print("уже поправлена:", p["id"]); continue
        for k, v in p["old"].items():
            if c.get(k) != v: sys.exit("карточка %s: поле %s не то, что ждали:\n  есть: %r\n  ждали: %r" % (p["id"], k, c.get(k), v))
        for k, v in p["new"].items():
            if k != "always" and len(v) > 400: sys.exit("карточка %s: %s длиннее 400 знаков (%d)" % (p["id"], k, len(v)))
            c[k] = v
        done.append(p["id"])
    json.dump(d, open(dst, "w", encoding="utf-8"), ensure_ascii=False, separators=(",", ":"))
    print("поправлено:", ", ".join(done) or "ничего", "| карточек", len(d["cards"]))

if __name__ == "__main__": main(sys.argv[1], sys.argv[2])
