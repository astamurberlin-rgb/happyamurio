import assert from 'node:assert/strict';
import vm from 'node:vm';
import {readFile} from 'node:fs/promises';
const source=await readFile(new URL('../shared/profile-storage.js',import.meta.url),'utf8');
const makeStore=()=>{const data=new Map();return {getItem:k=>data.has(k)?data.get(k):null,setItem:(k,v)=>data.set(k,String(v)),data}};
const context={};vm.runInNewContext(source,context);
const store=makeStore(),create=(app='day')=>context.HappyProfiles.create(app,{storage:store,reload(){}});
store.setItem('hd_db_v1','local diary');
const local=create();assert.equal(local.getSync('hd_db_v1'),'local diary');
store.setItem('hd_cloud_v1',JSON.stringify({s:{uid:'amurio'}}));
assert.equal(local.changed('amurio'),true);assert.equal(local.matches('amurio'),false);
const amurio=create();assert.equal(amurio.getSync('hd_db_v1'),null,'A new account cannot inherit an anonymous journal');
store.setItem(amurio.key('hd_db_v1'),'Amurio imported diary');
store.setItem('hd_cloud_v1',JSON.stringify({s:{uid:'second-user'}}));
const other=create();assert.equal(other.getSync('hd_db_v1'),null);assert.notEqual(other.key('hd_db_prev_v1'),amurio.key('hd_db_prev_v1'));
store.setItem('hd_cloud_v1',JSON.stringify({s:{uid:'amurio'}}));
assert.equal(create().getSync('hd_db_v1'),'Amurio imported diary');
store.setItem('hd_cloud_v1',JSON.stringify({s:null}));
assert.equal(create().getSync('hd_db_v1'),'local diary');
const old=makeStore();old.setItem('hd_cloud_v1',JSON.stringify({s:{uid:'existing'}}));old.setItem('hd_db_v1','existing diary');
const migrated=context.HappyProfiles.create('day',{storage:old});
assert.equal(migrated.getSync('hd_db_v1'),'existing diary');assert.equal(old.getItem('hd_db_v1'),'existing diary');
await migrated.write('hd_cfg_v1','settings',async(k,v)=>old.setItem(k,v));assert.equal(old.getItem(migrated.key('hd_cfg_v1')),'settings');
assert.equal(await migrated.read('hd_db_v1',async k=>old.getItem(k),async(k,v)=>old.setItem(k,v)),'existing diary');
const sport=makeStore();sport.setItem('hd_cloud_v1',JSON.stringify({s:{uid:'other'}}));sport.setItem('happy-sport-prototype-v1',JSON.stringify({sportOwner:'original',workouts:[{id:'private'}]}));
assert.equal(context.HappyProfiles.create('sport',{storage:sport}).getSync('happy-sport-prototype-v1'),null);
const blocked={getItem(){throw new Error('blocked')},setItem(){throw new Error('blocked')}};
assert.equal(context.HappyProfiles.create('day',{storage:blocked}).getSync('hd_db_v1'),null,'Unavailable storage must not prevent the UI opening');
const full=makeStore();full.setItem('hd_cloud_v1',JSON.stringify({s:{uid:'existing'}}));full.setItem('happy-profile-legacy-owner:day','existing');full.setItem('hd_db_v1','recoverable diary');full.setItem=()=>{throw new Error('quota')};
assert.equal(context.HappyProfiles.create('day',{storage:full}).getSync('hd_db_v1'),'recoverable diary','A failed migration copy cannot hide the original journal');
console.log('Passed: local/Amurio/second account separation, return to existing journals, legacy copy, backup keys and Sport ownership.');
for(const file of ['day/index.html','meal/index.html','sport/src/happy-auth.js']){
 const code=await readFile(new URL('../'+file,import.meta.url),'utf8');
 const start=code.indexOf('async function clSignIn('),end=code.indexOf('async function clSignOut(',start);
 let sent,stored=false;
 const auth=vm.createContext({K:{db:'db',cfg:'cfg'},DB:{},CFG:{},rawSet:async()=>{},CL:{},clAuth:async(path,body)=>{sent={path,body};return{}},clSes:j=>({uid:j.user.id}),clDerive:async()=>{},clStore:async()=>{stored=true},HappyProfile:{changed:()=>true}});
 vm.runInContext(code.slice(start,end),auth);
 assert.equal(await auth.clSignIn('amurio@example.test','not-a-real-password','up',' Amurio '),'confirm');
 assert.equal(sent.path,'signup');assert.equal(sent.body.data.display_name,'Amurio');assert.equal(stored,false,'Unconfirmed signup must not switch profiles');
 auth.clAuth=async()=>({access_token:'synthetic',user:{id:'new-owner'}});
 assert.equal(await auth.clSignIn('amurio@example.test','not-a-real-password','in',''),'reload');
 assert.equal(stored,true,'Persist the new session before reloading');
}
console.log('Passed: signup display name, email confirmation and account-switch reload in Day, Meal and Sport.');
